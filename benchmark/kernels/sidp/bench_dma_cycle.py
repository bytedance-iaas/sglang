#!/usr/bin/env python3
"""One-cycle, multi-process SiDP DMA Graph benchmark, without model compute.

Compare production compute-order cudaMemcpyAsync capture with Event or
generation-flag publication against production dynamic-owner conditional DMA
capture. All local slots are already writable. No GEMM, compute-side RAW/WAR
waits, cross-forward refill, or in-Graph barrier.
Host launch offsets simulate independently launched DP graphs. They are NOT
included in the CUDA-Event cycle duration; actual host launch skew is reported.

Default component sizes match Gemma4 BF16 gate_up/down (225 + 112.5 MiB).
Sources contain generated byte patterns, not checkpoint weights. No model load.
"""

