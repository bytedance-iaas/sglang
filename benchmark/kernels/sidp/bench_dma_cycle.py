class CycleGraph:
    def __init__(self, rank, k, args, copier, source_ptrs, destinations, owner_ptrs):
        import torch
        from sglang.kernels.ops.sidp import publish_generation
        from sglang.kernels.ops.sidp.dma_graph import load_sidp_dma_graph_module
        from sglang.srt.layers.sidp.scheduler import remote_positions

        self.torch = torch
        self.rank = rank
        self.layers = candidates(rank, args.num_gpus, k)
        assert self.layers == remote_positions(rank, args.num_gpus, k)
        count = len(self.layers)
        self.destinations = destinations
        self.component_bytes = args.component_bytes
        self.trace_steps = args.trace_steps
        self.stream = torch.cuda.Stream()
        self.owner_ptrs = owner_ptrs
        self.owners = torch.tensor(self.layers, dtype=torch.int32, device=rank)
        self.slots = torch.arange(count, dtype=torch.int32, device=rank)
        self.done = torch.empty(count, dtype=torch.uint8, device=rank)
        self.fill = torch.zeros(count, dtype=torch.int32, device=rank)
        self.comp = torch.zeros_like(self.fill)  # all slots writable, no consumer
        self.cursor = torch.zeros(1, dtype=torch.int32, device=rank)
        self.selected = torch.empty_like(self.cursor)
        self.error = torch.zeros_like(self.cursor)
        self.spins = torch.zeros(1, dtype=torch.int64, device=rank)
        self.collisions = torch.zeros_like(self.spins)
        self.copies = torch.tensor(
            [
                [
                    (
                        source_ptrs[owner][component],
                        destinations[component][slot].data_ptr(),
                        size,
                    )
                    for slot, owner in enumerate(self.layers)
                ]
                for component, size in enumerate(args.component_bytes)
            ],
            dtype=torch.uint64,
            device="cpu",
        )
        self.ready = [torch.cuda.Event() for _ in self.layers]
        self.graphs = {}
        self.events = {}
        self.step_events = {}
        self.trace_tensors = {}
        self.event_handles = {}
        module = load_sidp_dma_graph_module()
        self.publish_generation = publish_generation
        timeout = int(
            torch.cuda.get_device_properties(rank).clock_rate
            * 1000
            * args.device_timeout_s
        )

        for mode in MODES:
            # Match SidpGraphProfiler: internal capture events may become only
            # dependency edges and have no timestamp after replay.
            start, end = torch.cuda.Event(
                enable_timing=True, external=True
            ), torch.cuda.Event(enable_timing=True, external=True)
            steps = (
                [
                    [
                        torch.cuda.Event(enable_timing=True, external=True)
                        for _ in range(3)
                    ]
                    for _ in self.layers
                ]
                if args.trace_steps
                else []
            )
            if args.trace_steps:
                for row in steps:
                    for event in row:
                        event.record(self.stream)  # initialize native handles
                handles = torch.tensor(
                    [[e.cuda_event for e in row] for row in steps], dtype=torch.uint64
                )
                selected_trace = torch.empty(count, dtype=torch.int32, device=rank)
                spins_trace = torch.empty(count, dtype=torch.int64, device=rank)
                collisions_trace = torch.empty_like(spins_trace)
                self.trace_tensors[mode] = (
                    selected_trace,
                    spins_trace,
                    collisions_trace,
                )
                self.event_handles[mode] = handles
                trace_args = (selected_trace, spins_trace, collisions_trace, handles, 0)
            else:
                trace_args = (
                    self.selected,
                    self.spins,
                    self.collisions,
                    self.copies,
                    -1,
                )
            torch.cuda.synchronize()
            graph = torch.cuda.CUDAGraph(keep_graph=True)
            with torch.cuda.graph(graph, stream=self.stream):
                start.record(self.stream)
                if mode in ("compute_dma", "compute_dma_flag"):
                    for slot, owner in enumerate(self.layers):
                        if steps:
                            steps[slot][0].record(self.stream)
                            steps[slot][1].record(self.stream)
                        for component, size in enumerate(args.component_bytes):
                            copier.async_copy(
                                destinations[component][slot].data_ptr(),
                                source_ptrs[owner][component],
                                size,
                                self.stream.cuda_stream,
                            )
                        if mode == "compute_dma_flag":
                            self.publish_generation(self.fill, slot, 1)
                        else:
                            self.ready[slot].record(self.stream)
                        if steps:
                            steps[slot][2].record(self.stream)
                else:
                    module.append_cycle_to_capture(
                        owner_ptrs,
                        self.owners,
                        self.slots,
                        self.done,
                        self.fill,
                        self.comp,
                        self.cursor,
                        self.selected,
                        self.spins,
                        self.collisions,
                        self.error,
                        self.copies,
                        0,
                        1,
                        0,  # Preserve the benchmark's original rotating claim order.
                        rank,
                        args.backoff_ns,
                        timeout,
                        *trace_args,
                        self.copies,
                        self.selected,
                        self.selected,
                        -1,
                    )
                end.record(self.stream)
            graph.instantiate()
            self.graphs[mode] = graph
            self.events[mode] = (start, end)
            self.step_events[mode] = steps

    def clear_destinations(self):
        for component in self.destinations:
            for destination in component[: len(self.layers)]:
                destination.zero_()
        self.torch.cuda.synchronize()

    def validate(self, mode):
        if self.error.item() != 0:
            raise RuntimeError(f"rank {self.rank}: device error {self.error.item()}")
        if mode in FLAG_MODES and self.fill.tolist() != [1] * len(self.layers):
            raise RuntimeError(f"rank {self.rank}: unpublished destination")
        for component, buffers in enumerate(self.destinations):
            for slot, owner in enumerate(self.layers):
                expected = 1 + (owner * len(self.component_bytes) + component) % 251
                if not self.torch.all(buffers[slot] == expected).item():
                    raise RuntimeError(
                        f"copy mismatch: rank={self.rank}, owner={owner}, component={component}"
                    )

    def run(self, mode, target_ns, requested_offset_us):
        deadline = target_ns + round(requested_offset_us * 1000)
        remaining = (deadline - time.monotonic_ns()) / 1e9
        if remaining > 0:
            time.sleep(remaining)
        launched = time.monotonic_ns()
        # Replay under the same stream used for capture; no default-stream
        # Python work can accidentally become the measured graph's dependency.
        with self.torch.cuda.stream(self.stream):
            self.graphs[mode].replay()
        submitted = time.monotonic_ns()
        start, end = self.events[mode]
        end.synchronize()
        completed = time.monotonic_ns()
        ms = float(start.elapsed_time(end))
        result = {
            "rank": self.rank,
            "requested_offset_us": requested_offset_us,
            "launch_begin_ns": launched,
            "launch_submitted_ns": submitted,
            "completion_observed_ns": completed,
            "launch_lateness_us": (launched - deadline) / 1000,
            "cycle_ms": ms,
            "cycle_payload_bytes": len(self.layers) * sum(self.component_bytes),
            "effective_cycle_gbps": len(self.layers)
            * sum(self.component_bytes)
            / ms
            / 1e6,
        }
        if self.trace_steps:
            if mode == "dynamic_dma":
                selection, spins, collisions = (
                    t.tolist() for t in self.trace_tensors[mode]
                )
                if sorted(selection) != list(range(len(self.layers))):
                    raise RuntimeError(f"invalid candidate coverage: {selection}")
            else:
                selection = list(range(len(self.layers)))
                spins = collisions = [0] * len(self.layers)
            result["steps"] = [
                {
                    "step": i,
                    "owner": self.layers[selection[i]],
                    "slot": selection[i],
                    "claim_spins": spins[i],
                    "claim_collisions": collisions[i],
                    "claim_start_ms": start.elapsed_time(row[0]),
                    "claim_ms": (
                        row[0].elapsed_time(row[1]) if mode == "dynamic_dma" else 0
                    ),
                    "transfer_start_ms": start.elapsed_time(row[1]),
                    "transfer_window_ms": row[1].elapsed_time(row[2]),
                    "step_end_ms": start.elapsed_time(row[2]),
                    "payload_bytes": sum(self.component_bytes),
                }
                for i, row in enumerate(self.step_events[mode])
            ]
        return result


def worker(rank, args, port):
    import torch
    import torch.distributed as dist
    from sglang.kernels.ops.sidp import (
        load_sidp_sm_copy_module,
        native_peer_atomic_supported,
    )
    from sglang.srt.layers.sidp.cuda_memcpy import SidpCudaMemcpy

    torch.set_num_threads(1)
    torch.cuda.set_device(rank)
    dist.init_process_group(
        "gloo",
        init_method=f"tcp://127.0.0.1:{port}",
        rank=rank,
        world_size=args.num_gpus,
        timeout=timedelta(seconds=300),
    )
    copier = SidpCudaMemcpy()
    # One source per component per owner; K only changes which owners to skip.
    sources = [
        torch.full(
            (size,),
            1 + (rank * len(args.component_bytes) + i) % 251,
            dtype=torch.uint8,
            device=rank,
        )
        for i, size in enumerate(args.component_bytes)
    ]
    owner = torch.full((1,), -1, dtype=torch.int32, device=rank)
    destinations = [
        [torch.empty_like(source) for _ in range(args.num_gpus - min(args.k_values))]
        for source in sources
    ]
    torch.cuda.synchronize()
    descriptor = {
        "components": [
            copier.export_ipc_pointer(t.data_ptr(), t.nbytes) for t in sources
        ],
        "owner": copier.export_ipc_pointer(owner.data_ptr(), owner.nbytes),
    }
    descriptors = [None] * args.num_gpus
    dist.all_gather_object(descriptors, descriptor)
    mappings = {}

    def pointer(desc):
        if desc["handle"] not in mappings:
            mappings[desc["handle"]] = copier.open_ipc_allocation(desc["handle"])
        return mappings[desc["handle"]] + desc["offset"]

    source_ptrs, owner_ptr_values, atomic_support = [], [], []
    for peer in range(args.num_gpus):
        supported = peer == rank or native_peer_atomic_supported(rank, peer)
        atomic_support.append(supported)
        if not supported:
            raise RuntimeError(f"native peer atomic unavailable: {rank} -> {peer}")
        if peer == rank:
            source_ptrs.append([t.data_ptr() for t in sources])
            owner_ptr_values.append(owner.data_ptr())
        else:
            copier.enable_peer_access(peer)
            source_ptrs.append([pointer(d) for d in descriptors[peer]["components"]])
            owner_ptr_values.append(pointer(descriptors[peer]["owner"]))
    owner_ptrs = torch.tensor(owner_ptr_values, dtype=torch.uint64, device=rank)
    load_sidp_sm_copy_module()
    support_by_rank = [None] * args.num_gpus
    dist.all_gather_object(support_by_rank, atomic_support)
    payload = {
        **vars(args),
        "status": "running",
        "timestamp": datetime.now().astimezone().isoformat(),
        "device": torch.cuda.get_device_name(rank),
        "torch": torch.__version__,
        "cuda": torch.version.cuda,
        "native_peer_atomics": support_by_rank,
        "cases": [],
    }
    raw_file = None
    if rank == 0:
        raw_file = (
            Path(args.output).with_suffix(".samples.jsonl").open("x", encoding="utf-8")
        )

    def launch_round(graph, mode, offsets):
        deadline = [
            time.monotonic_ns() + round(args.lead_ms * 1e6) if rank == 0 else None
        ]
        dist.broadcast_object_list(deadline, src=0)
        local = graph.run(mode, deadline[0], offsets[rank])
        results = [None] * args.num_gpus
        # Everyone has completed their own Graph before participating here.
        dist.all_gather_object(results, local)
        return results

    for k in args.k_values:
        graph = CycleGraph(rank, k, args, copier, source_ptrs, destinations, owner_ptrs)
        torch.cuda.synchronize()
        dist.barrier()
        for base_offsets in args.offset_scenarios:
            # Correctness validation and warmup are excluded from samples.
            for mode in MODES:
                graph.clear_destinations()
                dist.barrier()
                launch_round(graph, mode, base_offsets)
                graph.validate(mode)
                # No rank may launch while another rank is doing validation.
                dist.barrier()
            for warmup in range(args.warmup):
                offsets = planned_offsets(
                    base_offsets, args.jitter_us, args.seed, -warmup - 1
                )
                for mode in MODES:
                    launch_round(graph, mode, offsets)
            records = {mode: [] for mode in MODES}
            for sample in range(args.iterations):
                offsets = planned_offsets(
                    base_offsets, args.jitter_us, args.seed, sample
                )
                order = MODE_ORDERS[sample % len(MODE_ORDERS)]
                for mode in order:
                    ranks = launch_round(graph, mode, offsets)
                    record = {
                        "k": k,
                        "mode": mode,
                        "sample": sample,
                        "base_offsets_us": base_offsets,
                        "jitter_us": args.jitter_us,
                        "requested_offsets_us": offsets,
                        "ranks": ranks,
                        "metrics": trial_metrics(
                            ranks, (args.num_gpus - k) * sum(args.component_bytes)
                        ),
                    }
                    records[mode].append(record)
                    if raw_file is not None:
                        raw_file.write(json.dumps(record) + "\n")
                        raw_file.flush()
            # All measured copies have completed before inspecting owner state.
            dist.barrier()
            if owner.item() != -1 or graph.error.item() != 0:
                raise RuntimeError(
                    f"rank {rank}: owner not FREE / device error after scenario"
                )
            dist.barrier()
            if rank == 0:
                summaries = {
                    mode: summarize(records[mode], args.num_gpus) for mode in MODES
                }
                ratio = (
                    summaries["dynamic_dma"]["max_rank_cycle_ms"]["p50"]
                    / summaries["compute_dma"]["max_rank_cycle_ms"]["p50"]
                )
                flag_to_event = (
                    summaries["compute_dma_flag"]["max_rank_cycle_ms"]["p50"]
                    / summaries["compute_dma"]["max_rank_cycle_ms"]["p50"]
                )
                dynamic_to_flag = (
                    summaries["dynamic_dma"]["max_rank_cycle_ms"]["p50"]
                    / summaries["compute_dma_flag"]["max_rank_cycle_ms"]["p50"]
                )
                payload["cases"].append(
                    {
                        "k": k,
                        "base_offsets_us": base_offsets,
                        "jitter_us": args.jitter_us,
                        "delay_scenario": delay_scenario_label(
                            base_offsets, args.jitter_us
                        ),
                        "modes": summaries,
                        "flag_to_event_cycle_ratio": flag_to_event,
                        "dynamic_to_flag_cycle_ratio": dynamic_to_flag,
                        "dynamic_to_compute_cycle_ratio": ratio,
                        "validation": "all payload bytes matched; all owner slots FREE",
                    }
                )
                write_report(args.output, payload)
                print(
                    f"K={k} delay={delay_scenario_label(base_offsets, args.jitter_us)}: "
                    f"event={summaries['compute_dma']['max_rank_cycle_ms']['p50']:.4f} ms, "
                    f"flag={summaries['compute_dma_flag']['max_rank_cycle_ms']['p50']:.4f} ms, "
                    f"dynamic={summaries['dynamic_dma']['max_rank_cycle_ms']['p50']:.4f} ms, "
                    f"flag/event={flag_to_event:.4f}, "
                    f"dynamic/flag={dynamic_to_flag:.4f}, "
                    f"dynamic/event={ratio:.4f}",
                    flush=True,
                )
            dist.barrier()
        del graph  # references remain alive until all peers finish their Graphs
        torch.cuda.synchronize()
        dist.barrier()
    if rank == 0:
        payload["status"] = "complete"
        write_report(args.output, payload)
        raw_file.close()
        print(f"Saved {args.output} and .md / .samples.jsonl", flush=True)
    # Keep exported sources/control allocations alive until every peer is done.
    dist.barrier()
    dist.destroy_process_group()


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--num-gpus", type=int, default=8)
    parser.add_argument("--k-values", default="1,4")
    parser.add_argument(
        "--component-bytes",
        default="235929600,117964800",
        help="Comma-separated bytes per layer component; may append extras / unaligned tails",
    )
    parser.add_argument("--iterations", type=int, default=30)
    parser.add_argument("--warmup", type=int, default=3)
    offset = parser.add_mutually_exclusive_group()
    offset.add_argument(
        "--stagger-us",
        help="Sweep per-adjacent-rank offsets, default 0,250,1000; rank r starts at r*stagger",
    )
    offset.add_argument(
        "--rank-offsets-us",
        help="One explicit offset per rank, e.g. 0,0,0,0,0,0,0,2000",
    )
    parser.add_argument(
        "--jitter-us",
        type=float,
        default=0,
        help="Additional reproducible uniform [0,jitter] launch delay per rank/trial",
    )
    parser.add_argument("--seed", type=int, default=20260903)
    parser.add_argument(
        "--lead-ms",
        type=float,
        default=20,
        help="Future host deadline lead time; actual lateness is always reported",
    )
    parser.add_argument(
        "--trace-steps",
        action="store_true",
        help="Instrument each claim/transfer step; run separately from low-overhead benchmark",
    )
    parser.add_argument("--backoff-ns", type=int, default=500)
    parser.add_argument("--device-timeout-s", type=float, default=30)
    parser.add_argument(
        "--output", help="New JSON path; also writes .md and .samples.jsonl"
    )
    args = parser.parse_args(argv)
    try:
        args.k_values = list(
            dict.fromkeys(csv_numbers(args.k_values, int, 1, "--k-values"))
        )
        args.component_bytes = csv_numbers(
            args.component_bytes, int, 1, "--component-bytes"
        )
        if args.rank_offsets_us is not None:
            offsets = csv_numbers(args.rank_offsets_us, float, 0, "--rank-offsets-us")
            if len(offsets) != args.num_gpus:
                parser.error("--rank-offsets-us needs one entry per GPU")
            args.offset_scenarios = [offsets]
        else:
            gaps = csv_numbers(
                args.stagger_us or "0,250,1000", float, 0, "--stagger-us"
            )
            args.offset_scenarios = [
                [rank * gap for rank in range(args.num_gpus)] for gap in gaps
            ]
    except argparse.ArgumentTypeError as error:
        parser.error(str(error))
    if args.num_gpus < 2 or any(k >= args.num_gpus for k in args.k_values):
        parser.error("require num-gpus >= 2 and 1 <= K < num-gpus")
    if args.iterations < 1 or args.warmup < 0 or args.backoff_ns < 0:
        parser.error("iterations must be positive; warmup/backoff must be non-negative")
    if (
        not all(
            math.isfinite(x)
            for x in (args.jitter_us, args.lead_ms, args.device_timeout_s)
        )
        or args.jitter_us < 0
        or args.lead_ms <= 0
        or args.device_timeout_s <= 0
    ):
        parser.error("invalid jitter, lead time or device timeout")
    if args.output is None:
        args.output = f"check_logs/sidp_dma_cycle_{datetime.now():%Y%m%d_%H%M%S}.json"
    args.command = shlex.join([sys.executable, *sys.argv])
    return args


def main():
    args = parse_args()
    import torch

    if args.num_gpus > torch.cuda.device_count():
        raise RuntimeError("Not enough visible CUDA GPUs")
    try:
        args.git_commit = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=SGLANG_ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        args.git_commit = "unknown"
    args.source_sha256 = {
        str(path.relative_to(SGLANG_ROOT)): hashlib.sha256(
            path.read_bytes()
        ).hexdigest()
        for path in (
            Path(__file__).resolve(),
            SGLANG_ROOT / "python/sglang/kernels/jit/csrc/sidp/dma_graph.cuh",
            SGLANG_ROOT / "python/sglang/kernels/jit/csrc/sidp/sm_copy.cuh",
            SGLANG_ROOT / "python/sglang/srt/layers/sidp/cuda_memcpy.py",
        )
    }
    output = Path(args.output)
    for path in (
        output,
        output.with_suffix(".md"),
        output.with_suffix(".samples.jsonl"),
    ):
        if path.exists():
            raise FileExistsError(f"Refusing to overwrite benchmark evidence: {path}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        port = sock.getsockname()[1]
    torch.multiprocessing.spawn(
        worker, args=(args, port), nprocs=args.num_gpus, join=True
    )


if __name__ == "__main__":
    main()
