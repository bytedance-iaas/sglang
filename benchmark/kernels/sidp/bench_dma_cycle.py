SGLANG_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(SGLANG_ROOT / "python"))
MODES = ("compute_dma", "compute_dma_flag", "dynamic_dma")
FLAG_MODES = ("compute_dma_flag", "dynamic_dma")
MODE_ORDERS = tuple(permutations(MODES))


def csv_numbers(raw, cast, minimum, option):
    try:
        values = [cast(item.strip()) for item in raw.split(",")]
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"{option}: invalid numeric list") from error
    if not values or any(not math.isfinite(v) or v < minimum for v in values):
        raise argparse.ArgumentTypeError(f"{option}: values must be >= {minimum}")
    return values


def candidates(rank, world_size, k):
    """Same sorted non-local positions as production remote_positions()."""
    return [owner for owner in range(world_size) if (owner - rank) % world_size >= k]


def planned_offsets(base_us, jitter_us, seed, sample):
    # Recreated for each mode: all modes receive identical intended offsets.
    rng = random.Random(seed + sample)
    return [offset + rng.uniform(0, jitter_us) for offset in base_us]


def delay_scenario_label(base_us, jitter_us):
    if jitter_us == 0:
        return f"fixed offsets {base_us} us"
    random_part = f"independent U[0,{jitter_us:g}] us/rank/sample"
    if all(offset == 0 for offset in base_us):
        return random_part
    return f"base offsets {base_us} us + {random_part}"


def percentile(values, q):
    values = sorted(values)
    index = (len(values) - 1) * q
    lo, hi = math.floor(index), math.ceil(index)
    return values[lo] + (values[hi] - values[lo]) * (index - lo)


def trial_metrics(ranks, cycle_bytes):
    cycle_ms = [rank["cycle_ms"] for rank in ranks]
    first_launch = min(rank["launch_begin_ns"] for rank in ranks)
    last_launch = max(rank["launch_begin_ns"] for rank in ranks)
    last_done = max(rank["completion_observed_ns"] for rank in ranks)
    wall_ms = (last_done - first_launch) / 1e6
    return {
        "max_rank_cycle_ms": max(cycle_ms),
        "mean_rank_cycle_ms": statistics.mean(cycle_ms),
        "actual_host_launch_span_us": (last_launch - first_launch) / 1e3,
        "max_host_launch_lateness_us": max(r["launch_lateness_us"] for r in ranks),
        "all_rank_observed_wall_ms": wall_ms,
        # Host-observed span includes stagger + launch/completion observation.
        # Never substitute max(local GPU duration) for skewed all-rank makespan.
        "all_rank_observed_wall_gbps": len(ranks) * cycle_bytes / wall_ms / 1e6,
        "slowest_rank_cycle_gbps": cycle_bytes / max(cycle_ms) / 1e6,
    }


def summarize(records, world_size):
    result = {}
    for field in records[0]["metrics"]:
        values = [record["metrics"][field] for record in records]
        result[field] = {
            "p50": statistics.median(values),
            "p95": percentile(values, 0.95),
            "min": min(values),
            "max": max(values),
        }
    result["rank_cycle_ms_p50"] = [
        statistics.median(r["ranks"][rank]["cycle_ms"] for r in records)
        for rank in range(world_size)
    ]
    result["samples"] = len(records)
    return result


